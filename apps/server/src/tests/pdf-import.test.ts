import prisma from "../lib/prisma";

describe("Phase 4: PDF Bank Statement Import Test Suite", () => {
  beforeEach(async () => {
    importSessionStore.clearAllForTesting();
    await prisma.transaction.deleteMany({
      where: {
        userId: 1,
        externalId: { in: ["TEST001", "TEST002", "TEST003", "TEST004", "TEST005"] },
      },
    });
  });

  // =========================================================================
  // 1. File Type Detection & Format Safeguards
  // =========================================================================
  describe("1. PDF File Detection & Safeguards", () => {
    it("accepts valid PDF buffer with %PDF magic header", async () => {
      const buffer = await generateSection10Pdf();
      const fileType = detectAndValidateFileType(buffer, "statement.pdf");
      assert.equal(fileType, "pdf");
    });

    it("rejects non-PDF binary masquerading as PDF", () => {
      const fakeBuffer = Buffer.from([0x00, 0x01, 0x02, 0x03, 0x04]);
      assert.throws(
        () => detectAndValidateFileType(fakeBuffer, "fake.pdf"),
        (err: any) => err instanceof ValidationError && err.message.includes("does not match .pdf format")
      );
    });

    it("rejects empty PDF buffer", () => {
      const emptyBuffer = Buffer.alloc(0);
      assert.throws(
        () => detectAndValidateFileType(emptyBuffer, "empty.pdf"),
        (err: any) => err instanceof ValidationError && err.message.includes("empty")
      );
    });

    it("detects scanned PDF with no extractable text", async () => {
      const pdfDoc = await PDFDocument.create();
      pdfDoc.addPage([600, 400]); // Blank page without text items
      const bytes = await pdfDoc.save();

      await assert.rejects(
        async () => {
          await importService.parseUploadedFile("1", Buffer.from(bytes), "scanned.pdf");
        },
        (err: any) =>
          err instanceof ValidationError &&
          err.message.includes("scanned document or contains no extractable text")
      );
    });

    it("rejects PDF exceeding maximum page count", async () => {
      const pdfDoc = await PDFDocument.create();
      for (let i = 0; i < MAX_PDF_PAGES + 2; i++) {
        const page = pdfDoc.addPage([400, 300]);
        page.drawText(`Page ${i + 1}`);
      }
      const bytes = await pdfDoc.save();

      await assert.rejects(
        async () => {
          await importService.parseUploadedFile("1", Buffer.from(bytes), "huge.pdf");
        },
        (err: any) =>
          err instanceof ValidationError &&
          err.message.includes("maximum allowed page count")
      );
    });

    it("rejects document with text but no recognizable transaction table", async () => {
      const pdfDoc = await PDFDocument.create();
      const page = pdfDoc.addPage([600, 400]);
      page.drawText("This is a simple letter without any transaction table.");
      page.drawText("Sincerely, Management.");
      const bytes = await pdfDoc.save();

      await assert.rejects(
        async () => {
          await importService.parseUploadedFile("1", Buffer.from(bytes), "letter.pdf");
        },
        (err: any) =>
          err instanceof ValidationError &&
          err.message.includes("No transaction rows could be extracted")
      );
    });
  });

  // =========================================================================
  // 2. Table Header Detection & Multi-page Handling
  // =========================================================================
  describe("2. Table Extraction, Multi-page & Multi-line Narration", () => {
    it("handles multi-page PDF statements and skips repeated headers", async () => {
      const buffer = await generateMultiPagePdf();
      const meta = await importService.parseUploadedFile("1", buffer, "multipage.pdf");

      assert.equal(meta.fileType, "pdf");
      assert.equal(meta.totalRows, 2);
      assert.equal(meta.previewRows[0]["Description"], "Grocery Store");
      assert.equal(meta.previewRows[1]["Description"], "Pharmacy");
    });

    it("reconstructs wrapped multi-line descriptions into a single row", async () => {
      const buffer = await generateSection10Pdf();
      const meta = await importService.parseUploadedFile("1", buffer, "wrapped.pdf");

      const metroRow = meta.previewRows.find((r) => r["Narration"]?.includes("Metro travel"));
      assert.ok(metroRow);
      // Verify wrapped narration was stitched
      assert.ok(metroRow!["Narration"].includes("Station ID: Central-Line-99"));
    });

    it("correctly identifies columns and never maps Balance as transaction amount", async () => {
      const buffer = await generateSingleAmountPdf();
      const meta = await importService.parseUploadedFile("1", buffer, "single_amount.pdf");

      assert.ok(meta.headers.includes("Amount"));
      assert.ok(meta.headers.includes("Balance"));

      const mapping = meta.suggestedMapping;
      assert.equal(mapping.amountMode, "single_amount");
      assert.equal(mapping.amountColumn, "Amount");
      // Balance must NOT be mapped as amount
      assert.notEqual(mapping.amountColumn, "Balance");
    });
  });

  // =========================================================================
  // 3. Deterministic Section 10 Fixture Reconciliation & Idempotency
  // =========================================================================
  describe("3. Section 10 Deterministic PDF Fixture Reconciliation", () => {
    it("processes Section 10 PDF fixture: 4 debits imported (₹2,729.00), salary credit excluded, opening balance excluded, and re-import yields 0 increase", async () => {
      const pdfBuffer = await generateSection10Pdf();

      // 1. Upload & parse
      const meta = await importService.parseUploadedFile("1", pdfBuffer, "bank_statement.pdf");
      assert.equal(meta.fileType, "pdf");
      assert.equal(meta.totalRows, 6);

      // 2. Mapping
      const mapping: ColumnMapping = {
        dateColumn: "Date",
        descriptionColumn: "Narration",
        amountMode: "debit_credit",
        debitColumn: "Debit",
        creditColumn: "Credit",
        externalIdColumn: "Ref",
      };

      // 3. Preview
      const preview = await importService.generateImportPreview("1", meta.fileId, mapping, {
        dateFormat: "YYYY-MM-DD",
      });

      assert.equal(preview.summary.totalRows, 6);
      assert.equal(preview.summary.validExpenseCount, 4);
      assert.equal(preview.summary.excludedNonExpenseCount, 2);
      assert.equal(preview.summary.expectedToImportCount, 4);

      // Verify computed sum of eligible expenses
      const previewTotal = preview.sampleRows
        .filter((r) => r.status === "READY")
        .reduce((sum, r) => sum + (r.mapped.amount || 0), 0);
      assert.equal(previewTotal, 2729.00);

      // Verify exclusions
      const salaryRow = preview.sampleRows.find((r) => r.mapped.title?.includes("Salary credit"));
      assert.ok(salaryRow);
      assert.equal(salaryRow?.status, "EXCLUDED_NON_EXPENSE");
      assert.equal(salaryRow?.mapped.amount, 50000.00);

      const balanceRow = preview.sampleRows.find((r) => r.mapped.title?.includes("Opening Balance"));
      assert.ok(balanceRow);
      assert.equal(balanceRow?.status, "EXCLUDED_NON_EXPENSE");
      assert.equal(balanceRow?.mapped.amount, 2500.00);

      // 4. Confirm & Commit Import
      const commitResult = await importService.confirmAndCommitImport("1", {
        fileId: meta.fileId,
        mapping,
      });

      assert.equal(commitResult.imported, 4);
      assert.equal(commitResult.excludedNonExpense, 2);
      assert.equal(commitResult.importedIds.length, 4);

      // Verify records in DB
      let ledgerSum = 0;
      for (const idStr of commitResult.importedIds) {
        const tx = await transactionRepository.findTransactionById(Number(idStr));
        assert.ok(tx);
        assert.equal(tx?.source, TransactionSource.BANK_STATEMENT);
        ledgerSum += Number(tx?.amount);
      }
      assert.equal(ledgerSum, 2729.00);

      // 5. Re-import: verify idempotency and zero ledger increase
      const metaRetry = await importService.parseUploadedFile("1", pdfBuffer, "retry_statement.pdf");
      const previewRetry = await importService.generateImportPreview("1", metaRetry.fileId, mapping, {
        dateFormat: "YYYY-MM-DD",
      });

      assert.equal(previewRetry.summary.totalRows, 6);
      assert.equal(previewRetry.summary.validExpenseCount, 0); // All 4 are confirmed duplicates
      assert.equal(previewRetry.summary.confirmedDuplicateCount, 4);
      assert.equal(previewRetry.summary.excludedNonExpenseCount, 2);
      assert.equal(previewRetry.summary.expectedToImportCount, 0);

      const commitRetry = await importService.confirmAndCommitImport("1", {
        fileId: metaRetry.fileId,
        mapping,
      });

      assert.equal(commitRetry.imported, 0);
      assert.equal(commitRetry.importedIds.length, 0);

      // Cleanup transactions created for this test
      for (const idStr of commitResult.importedIds) {
        await transactionRepository.deleteTransaction(Number(idStr));
      }
    });
  });

  // =========================================================================
  // 4. Security & Tenant Isolation
  // =========================================================================
  describe("4. Security, Isolation & Edge Cases", () => {
    it("enforces tenant isolation: user 2 cannot access user 1's PDF session", async () => {
      const buffer = await generateSection10Pdf();
      const meta = await importService.parseUploadedFile("1", buffer, "user1.pdf");

      await assert.rejects(
        async () => {
          await importService.generateImportPreview("2", meta.fileId, {
            dateColumn: "Date",
            descriptionColumn: "Narration",
            amountMode: "debit_credit",
            debitColumn: "Debit",
            creditColumn: "Credit",
          });
        },
        (err: any) => err instanceof ForbiddenError
      );
    });
  });
});
